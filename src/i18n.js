let lang = (() => { try { return localStorage.getItem('noel.lang'); } catch { return null; } })() || (navigator.language?.startsWith('vi') ? 'vi' : 'en');
const subs = [];

export const getLang = () => lang;
export function t(key, vars) {
  const v = D[lang][key] ?? D.vi[key] ?? key;
  if (typeof v !== 'string' || !vars) return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
export function apply(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n, el.dataset.vars ? JSON.parse(el.dataset.vars) : undefined); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('noel.lang', l); } catch { /* ignore */ }
  document.documentElement.lang = l;
  apply();
  subs.forEach((f) => f(l));
}
export const onLang = (f) => subs.push(f);
